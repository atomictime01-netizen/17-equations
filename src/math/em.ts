/**
 * Electromagnetic field models used by the Maxwell experience. All are exact solutions for
 * the stated idealised geometry, not a general-purpose solver.
 *
 * 2-D slice convention: "charges" are infinitely long uniform line charges and "wires" infinitely
 * long straight currents, both perpendicular to the screen. Their fields fall off as 1/r, and
 * Gauss's and Ampère's laws hold exactly for any closed loop drawn in the plane:
 *   ∮ E·n̂ dl = λ_enc/ε₀        ∮ B·dl = μ₀ I_enc
 */
export const EPS0 = 8.8541878128e-12; // F/m
export const MU0 = 1.25663706212e-6; // N/A²
export const C_LIGHT = 299792458; // m/s (exact by definition of the metre)

export interface LineCharge {
  x: number;
  y: number;
  q: number; // linear charge density λ (nC/m in the UI)
}
export interface Wire {
  x: number;
  y: number;
  I: number; // current in amperes, + = out of screen
}

/** E field (V/m) at (x, y) in metres from line charges with λ in C/m. */
export function eField(charges: LineCharge[], x: number, y: number, scale = 1e-9): [number, number] {
  let ex = 0;
  let ey = 0;
  const k = 1 / (2 * Math.PI * EPS0);
  for (const c of charges) {
    const dx = x - c.x;
    const dy = y - c.y;
    const r2 = dx * dx + dy * dy + 1e-10;
    const f = (k * c.q * scale) / r2;
    ex += f * dx;
    ey += f * dy;
  }
  return [ex, ey];
}

/** Electric potential (V) up to a constant: φ = −(λ/2πε₀) ln r. */
export function ePotential(charges: LineCharge[], x: number, y: number, scale = 1e-9): number {
  let p = 0;
  const k = 1 / (2 * Math.PI * EPS0);
  for (const c of charges) p -= k * c.q * scale * 0.5 * Math.log((x - c.x) ** 2 + (y - c.y) ** 2 + 1e-10);
  return p;
}

/** B field (T) of long straight wires: |B| = μ₀I/(2πr), circulating by the right-hand rule. */
export function bField(wires: Wire[], x: number, y: number): [number, number] {
  let bx = 0;
  let by = 0;
  const k = MU0 / (2 * Math.PI);
  for (const w of wires) {
    const dx = x - w.x;
    const dy = y - w.y;
    const r2 = dx * dx + dy * dy + 1e-10;
    const f = (k * w.I) / r2;
    // ẑ × r̂ = (−dy, dx)
    bx += -f * dy;
    by += f * dx;
  }
  return [bx, by];
}

/** Numerical outward flux ∮ F·n̂ dl around a circle (midpoint rule). */
export function circleFlux(field: (x: number, y: number) => [number, number], cx: number, cy: number, R: number, n = 720): number {
  let s = 0;
  const dl = (2 * Math.PI * R) / n;
  for (let i = 0; i < n; i++) {
    const a = ((i + 0.5) / n) * 2 * Math.PI;
    const nx = Math.cos(a);
    const ny = Math.sin(a);
    const [fx, fy] = field(cx + R * nx, cy + R * ny);
    s += (fx * nx + fy * ny) * dl;
  }
  return s;
}

/** Numerical circulation ∮ F·dl around a circle, counter-clockwise. */
export function circleCirculation(field: (x: number, y: number) => [number, number], cx: number, cy: number, R: number, n = 720): number {
  let s = 0;
  const dl = (2 * Math.PI * R) / n;
  for (let i = 0; i < n; i++) {
    const a = ((i + 0.5) / n) * 2 * Math.PI;
    const tx = -Math.sin(a);
    const ty = Math.cos(a);
    const [fx, fy] = field(cx + R * Math.cos(a), cy + R * Math.sin(a));
    s += (fx * tx + fy * ty) * dl;
  }
  return s;
}

/**
 * Faraday's law for a uniform field B(t) inside a long solenoid of radius a:
 * the induced electric field circulates with
 *   E_φ(r) = −(r/2) dB/dt          (r < a)
 *   E_φ(r) = −(a²/(2r)) dB/dt      (r ≥ a)
 */
export function inducedE(r: number, a: number, dBdt: number): number {
  return r < a ? -(r / 2) * dBdt : -((a * a) / (2 * r)) * dBdt;
}

/**
 * 1-D FDTD (Yee) solver for a plane wave travelling along x with fields E_y and B_z in
 * normalised units (c = 1 in vacuum, Δx = 1, Δt = S·Δx/c). Relative permittivity/permeability
 * per cell slow the wave to c/√(ε_r μ_r).
 * When the displacement current is disabled, ∂E/∂t is no longer generated by ∇×B, and the
 * fields cannot sustain a propagating wave — the point Maxwell's correction makes.
 */
export class Yee1D {
  readonly n: number;
  E: Float64Array;
  B: Float64Array;
  epsR: Float64Array;
  muR: Float64Array;
  courant = 1;
  displacement = true;
  time = 0;
  constructor(n: number) {
    this.n = n;
    this.E = new Float64Array(n);
    this.B = new Float64Array(n);
    this.epsR = new Float64Array(n).fill(1);
    this.muR = new Float64Array(n).fill(1);
  }
  reset() {
    this.E.fill(0);
    this.B.fill(0);
    this.time = 0;
  }
  step(source: number, sourceIndex = 2) {
    const { n, E, B, epsR, muR } = this;
    const S = this.courant;
    const eLeft = E[1];
    const eRight = E[n - 2];
    // Faraday: ∂B/∂t = −∂E/∂x
    for (let i = 0; i < n - 1; i++) B[i] -= (S / muR[i]) * (E[i + 1] - E[i]);
    // Ampère–Maxwell: ∂E/∂t = (1/ε)(−∂B/∂x) − J/ε
    if (this.displacement) {
      for (let i = 1; i < n; i++) E[i] -= (S / epsR[i]) * (B[i] - B[i - 1]);
      E[sourceIndex] += source;
    } else {
      // without ∂E/∂t the electric field is fixed by the source alone
      E.fill(0);
      E[sourceIndex] = source * 6;
    }
    // first-order Mur absorbing boundaries (exact for S = 1 in vacuum)
    E[n - 1] = eRight;
    E[0] = eLeft;
    this.time += S;
  }
}
